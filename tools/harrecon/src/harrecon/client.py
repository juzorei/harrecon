"""Generate a typed Python client skeleton from a captured endpoint."""

from __future__ import annotations

import re
from urllib.parse import urlsplit

from .har import ApiCall, schema_for

_TYPE_MAP = {"string": "str", "int": "int", "number": "float", "bool": "bool",
             "null": "None", "unknown": "object"}


def class_name_for(call: ApiCall) -> str:
    """GET /api/lots/{id} -> LotsIdResponse-ish: derive from the last path segment."""
    path = call.entries[0].path.rstrip("/")
    tail = re.split(r"[/_-]", path.rsplit("/", 1)[-1].replace("{id}", ""))
    words = [w for w in tail if w and not w.isdigit()]
    base = "".join(w.capitalize() for w in words) or "Api"
    return base + "Response"


def _py_type(schema: dict) -> str:
    t = schema.get("type", "object")
    if t == "array":
        return f"list[{_py_type(schema.get('items', {}))}]"
    if t == "object":
        return "dict[str, object]"
    if "|" in t:
        return " | ".join(_TYPE_MAP.get(part, part) for part in t.split("|"))
    return _TYPE_MAP.get(t, "object")


def _dataclass(name: str, schema: dict, out: list[str], depth: int = 0) -> str:
    fields = schema.get("fields", {})
    if not fields:
        return "dict[str, object]"
    cls = f"{name}Data" if depth else name
    out.append("@dataclass")
    out.append(f"class {cls}:")
    inner_classes = []
    for key, sub in fields.items():
        attr = re.sub(r"\W", "_", key) or "field"
        py = _py_type(sub)
        if sub.get("type") == "object" and sub.get("fields"):
            inner = _dataclass(f"{cls}{attr.capitalize()}", sub, out, depth + 1)
            py = inner
        elif sub.get("type") == "array" and isinstance(sub.get("items"), dict) and sub["items"].get("fields"):
            inner = _dataclass(f"{cls}{attr.capitalize()}Item", sub["items"], out, depth + 1)
            py = f"list[{inner}]"
        if sub.get("optional"):
            py = f"{py} | None = None"
        out.append(f"    {attr}: {py}")
    if not fields:
        out.append("    pass")
    out.append("")
    return cls


def generate(call: ApiCall) -> str:
    entry = call.entries[0]
    schema = schema_for(call)
    name = class_name_for(call)
    parts = urlsplit(entry.request_headers.get("referer", "") or f"https://{call.host}")
    out = [
        '"""Generated by harrecon from a HAR capture. Review before use."""',
        "from dataclasses import dataclass",
        "import json",
        "import urllib.request",
        "",
        "",
    ]
    body_lines: list[str] = []
    dataclass_name = _dataclass(name, schema, body_lines)
    out += body_lines
    path_pattern = re.sub(r"/\d{3,}(?=/|$)", "/{id}", entry.path)
    query = f"?{entry.query}" if entry.query else ""
    url = f"{entry.scheme}://{entry.host}{path_pattern}{query}"
    auth = entry.request_headers.get("authorization", "")
    auth_line = f'    "Authorization": "{auth}",' if auth else "    # add auth headers as captured"
    out += [
        "",
        "def fetch() -> " + dataclass_name + ":",
        f'    url = "{url}"',
        "    request = urllib.request.Request(url, headers={",
        auth_line,
        "    })",
        "    with urllib.request.urlopen(request, timeout=30) as response:",
        "        payload = json.load(response)",
        f"    # TODO: validate/parse payload into {dataclass_name} — the schema above is the captured shape",
        "    return payload",
        "",
    ]
    return "\n".join(out)
